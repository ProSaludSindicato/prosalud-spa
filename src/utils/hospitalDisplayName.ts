function resolveHospitalCodeToLabel(raw: string): string {
  const trimmed = raw.trim();
  if (trimmed === '') return trimmed;
  if (hospitalMap[trimmed]) {
    return hospitalMap[trimmed];
  }
  const upper = trimmed.toUpperCase();
  const entry = Object.entries(hospitalMap).find(([k]) => k.trim().toUpperCase() === upper);
  return entry ? entry[1] : trimmed;
}

/** Convierte el código interno de hospital al nombre legible que conoce el afiliado. */
export function getHospitalDisplayName(hospitalValue: string | null | undefined): string {
  if (!hospitalValue) return '';

  const hospitalPermitido = hospitalesPermitidos.find(
    (h) => h.key === hospitalValue || h.key === hospitalValue.trim(),
  );
  if (hospitalPermitido) {
    return hospitalPermitido.displayName;
  }

  const displayName = resolveHospitalCodeToLabel(hospitalValue);
  return displayName.toUpperCase();
}

/** Dado el nombre legible del hospital, obtiene la clave/código interno asociado. */
export function getHospitalKeyFromDisplay(displayName: string): string {
  const hospital = hospitalesPermitidos.find(
    (h) =>
      h.displayName.toUpperCase().trim() === displayName.toUpperCase().trim(),
  );
  return hospital?.key || displayName;
}
