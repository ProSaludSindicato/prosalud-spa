const hospitalMap = HOSPITAL_CODE_TO_LABEL;

export type ConvenioHospitalOption = { readonly value: string; readonly label: string };

/** Opciones ordenadas por etiqueta para selects de sede/cliente en convenios. */
export function buildConvenioHospitalOptions(): ConvenioHospitalOption[] {
  return Object.entries(HOSPITAL_CODE_TO_LABEL)
    .map(([value, label]) => ({ value, label }))
    .sort((a, b) => a.label.localeCompare(b.label, 'es', { sensitivity: 'base' }));
}

